<?php

declare(strict_types=1);

require_once __DIR__ . '/password_change_common.php';
require_once __DIR__ . '/app_session_common.php';

pc_bootstrap_json_endpoint();

$conn = null;
$transactionStarted = false;

try {
    pc_require_post();

    $oldChallengeToken = pc_post_string('challenge_token');
    $oldTokenHash = pc_challenge_token_hash($oldChallengeToken);
    $config = pc_security_config();
    pc_email_config($config);

    $conn = pc_open_database();
    $appSession = as_require_session($conn, false);
    $preview = pc_challenge_preview($conn, $oldTokenHash);
    if ($preview === null) {
        pc_reject('The password-change request is invalid or has expired.');
    }

    $role = pc_normalize_role((string)$preview['role']);
    $accountSource = (string)$preview['account_source'];
    $userId = (string)$preview['user_id'];
    pc_validate_user_id($userId);
    as_assert_session_identity($appSession, $role, $userId, $accountSource);

    if (!$conn->begin_transaction()) {
        throw new RuntimeException('Password-change transaction could not start.');
    }
    $transactionStarted = true;

    $account = pc_fetch_account_for_update(
        $conn,
        $role,
        $userId,
        $accountSource
    );
    $canonicalUserId = (string)$account['user_id'];
    if (!hash_equals($userId, $canonicalUserId)) {
        throw new RuntimeException('Password-change account ID binding changed unexpectedly.');
    }
    $userId = $canonicalUserId;
    $challenge = pc_challenge_for_update($conn, $oldTokenHash);
    if ($challenge === null
        || (int)$challenge['challenge_id'] !== (int)$preview['challenge_id']
        || (string)$challenge['role'] !== $role
        || (string)$challenge['account_source'] !== $accountSource
        || (string)$challenge['user_id'] !== $userId
    ) {
        throw new RuntimeException('Challenge binding changed unexpectedly.');
    }

    pc_assert_pending_challenge($challenge);
    if (pc_normalize_method((string)$challenge['method']) !== 'email') {
        pc_reject('Authenticator codes are generated by your app and cannot be resent.');
    }
    if ((int)($challenge['challenge_expired'] ?? 1) === 1) {
        pc_expire_challenge($conn, (int)$challenge['challenge_id']);
        if (!$conn->commit()) {
            throw new RuntimeException('Expired challenge could not be committed.');
        }
        $transactionStarted = false;
        pc_reject('The password-change request expired. Start a new request.');
    }

    $currentFingerprint = pc_account_fingerprint(
        $role,
        $accountSource,
        $userId,
        $account['password_value'],
        $config
    );
    if (!hash_equals((string)$challenge['account_fingerprint'], $currentFingerprint)) {
        pc_mark_challenge_cancelled($conn, $oldTokenHash);
        if (!$conn->commit()) {
            throw new RuntimeException('Stale challenge could not be committed.');
        }
        $transactionStarted = false;
        pc_reject(
            'Your account password changed after this request started. Start a new password-change request.'
        );
    }

    $resendCount = (int)($challenge['resend_count'] ?? 0);
    if ($resendCount >= PC_MAX_RESENDS) {
        pc_reject('The resend limit was reached. Start a new password-change request.');
    }

    $secondsSinceLastSend = (int)($challenge['seconds_since_last_send'] ?? 0);
    if ($secondsSinceLastSend < PC_RESEND_COOLDOWN_SECONDS) {
        $retryAfter = PC_RESEND_COOLDOWN_SECONDS - max(0, $secondsSinceLastSend);
        pc_reject(
            'Please wait before requesting another verification code.',
            ['retry_after' => $retryAfter]
        );
    }

    $destinationEncrypted = (string)($challenge['destination_encrypted'] ?? '');
    if ($destinationEncrypted === '') {
        throw new RuntimeException('Email destination is missing.');
    }
    $destination = pc_decrypt_email_destination(
        $destinationEncrypted,
        $role,
        $accountSource,
        $userId,
        $config
    );

    $newTokenData = pc_new_challenge_token();
    $newChallengeToken = $newTokenData['token'];
    $newTokenHash = $newTokenData['hash'];
    $emailOtp = pc_generate_email_otp();
    $newOtpHash = pc_email_otp_hash($newTokenHash, $emailOtp, $config);

    $statement = pc_prepare(
        $conn,
        'UPDATE password_change_challenges '
            . 'SET challenge_token_hash = ?, otp_hash = ?, '
            . 'otp_expires_at = DATE_ADD(NOW(6), INTERVAL 5 MINUTE), '
            . 'expires_at = DATE_ADD(NOW(6), INTERVAL 5 MINUTE), '
            . 'resend_count = resend_count + 1, last_sent_at = NOW(6) '
            . "WHERE challenge_id = ? AND status = 'pending'"
    );
    $challengeId = (int)$challenge['challenge_id'];
    $statement->bind_param('ssi', $newTokenHash, $newOtpHash, $challengeId);
    if (!$statement->execute() || $statement->affected_rows !== 1) {
        $statement->close();
        throw new RuntimeException('Verification code could not be renewed.');
    }
    $statement->close();
    as_record_activity(
        $conn,
        $appSession,
        'password_change_otp_resent',
        ['verification_method' => 'email'],
        'server',
        'info',
        $config
    );

    if (!$conn->commit()) {
        throw new RuntimeException('Password-change transaction could not be committed.');
    }
    $transactionStarted = false;

    $sent = pc_send_email_otp(
        $config,
        $destination,
        $emailOtp,
        [
            'purpose' => 'password_change',
            'role' => $role,
            'account_source' => $accountSource,
            'user_id' => $userId,
            'expires_in' => PC_CHALLENGE_TTL_SECONDS,
            'is_resend' => true,
        ]
    );
    if (!$sent) {
        if ($conn->begin_transaction()) {
            pc_mark_challenge_cancelled($conn, $newTokenHash);
            $conn->commit();
        }
        $conn->close();
        $conn = null;
        pc_reject('The verification email could not be sent. Start a new request.');
    }

    $maskedDestination = (string)($challenge['destination_masked'] ?? '');
    $conn->close();
    $conn = null;
    pc_respond([
        'status' => 'success',
        'message' => 'A new 6-digit verification code was sent.',
        'challenge_token' => $newChallengeToken,
        'method' => 'email',
        'expires_in' => PC_CHALLENGE_TTL_SECONDS,
        'destination' => $maskedDestination,
        'requires_totp_setup' => false,
        'totp_setup_key' => null,
        'otpauth_uri' => null,
    ]);
} catch (PasswordChangeClientException $error) {
    if ($transactionStarted && $conn instanceof mysqli) {
        $conn->rollback();
    }
    if ($conn instanceof mysqli) {
        $conn->close();
    }
    pc_respond(pc_client_error_payload($error->getMessage(), $error->details()));
} catch (Throwable $error) {
    if ($transactionStarted && $conn instanceof mysqli) {
        $conn->rollback();
    }
    if ($conn instanceof mysqli) {
        $conn->close();
    }
    error_log('resend_password_change_otp.php failed: ' . $error->getMessage());
    pc_respond([
        'status' => 'error',
        'message' => 'Password change is temporarily unavailable. Please try again later.',
    ]);
}
